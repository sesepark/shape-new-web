/**
 * SHAPE 와 함께 일하는 기관 목록.
 *
 * 이 목록은 **코드에 그대로 둡니다.** 관리자 화면에서 고치는 다른 목록(관련 링크·
 * 부원·장비)과 다른데, 기관은 한 학기에 한두 곳 늘까 말까 하고 한번 적으면 거의
 * 바뀌지 않기 때문입니다. 표 하나와 창구 네 개와 관리자 탭 하나를 그 빈도를 위해
 * 두는 것보다, 아래 배열에 한 덩이를 더 적는 편이 낫습니다.
 *
 * 기관을 추가하려면 아래 배열에 항목 하나를 넣으면 됩니다. 마크(로고)가 있으면
 * 파일을 `public/partners/` 에 두고 `logo` 에 `/partners/파일이름` 을 적습니다.
 * 마크가 없으면 그 칸을 비워 둡니다 — 카드가 이름을 크게 쓰는 모습으로 바뀝니다.
 */
export type Partner = {
  /** 상위 소속. 카드에서 이름 위에 작게 놓입니다. 없으면 생략됩니다. */
  owner?: string;
  /** 기관 이름. 마크가 없을 때 이 이름이 카드의 주인공이 됩니다. */
  name: string;
  /** 어떤 기관인지 한 줄로. */
  description: string;
  /**
   * 마크 파일 경로. `public/` 아래의 파일을 `/partners/…` 로 가리킵니다.
   * 없으면(또는 비우면) 이름만 크게 나옵니다.
   */
  logo?: string;
  /**
   * 마크 원본의 가로세로. `next/image` 는 크기를 알아야 자리를 미리 잡아 두므로,
   * 이 값이 없으면 그림이 늦게 도착할 때 카드가 한 번 출렁입니다. 화면에 보이는
   * 크기는 CSS 가 정하고, 이 값은 비율을 알려 주는 용도입니다.
   */
  logoWidth?: number;
  logoHeight?: number;
};

